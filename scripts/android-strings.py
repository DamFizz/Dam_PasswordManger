"""
Copy the Android app's UI strings (English and Malay) into the web app, so both apps say the same thing.

Usage:  python scripts/android-strings.py [path-to-MyVaultAndroid]
Writes: src/i18n/android-en.ts and src/i18n/android-ms.ts (keys prefixed with "a.").
  %1$s / %1$d  ->  {1}      plurals -> "a.name.one" / "a.name.other"
Malay strings missing on Android fall back to English.
"""
import html
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANDROID = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(ROOT), 'MyVaultAndroid')
RES = os.path.join(ANDROID, 'app', 'src', 'main', 'res')


def clean(v: str) -> str:
    v = v.strip()
    if len(v) >= 2 and v[0] == '"' and v[-1] == '"':
        v = v[1:-1]
    v = re.sub(r'<[^>]+>', '', v)  # drop inline markup such as <b>
    v = html.unescape(v)
    v = v.replace("\\'", "'").replace('\\"', '"').replace('\\n', '\n').replace('\\@', '@').replace('\\?', '?')
    v = re.sub(r'%(\d+)\$[sd]', r'{\1}', v)
    v = re.sub(r'%[sd]', '{1}', v)
    return v.replace('%%', '%')


def parse(path: str) -> dict:
    s = open(path, encoding='utf8').read()
    out = {}
    for m in re.finditer(r'<string name="([^"]+)"[^>]*>(.*?)</string>', s, re.S):
        out['a.' + m.group(1)] = clean(m.group(2))
    for m in re.finditer(r'<plurals name="([^"]+)"[^>]*>(.*?)</plurals>', s, re.S):
        for q in re.finditer(r'<item quantity="([^"]+)">(.*?)</item>', m.group(2), re.S):
            out['a.%s.%s' % (m.group(1), q.group(1))] = clean(q.group(2))
    return out


en = parse(os.path.join(RES, 'values', 'strings.xml'))
ms_raw = parse(os.path.join(RES, 'values-ms', 'strings.xml'))
def ms_value(k, v):
    if k in ms_raw:
        return ms_raw[k]
    # Malay has no singular form: use its plural form rather than English
    if k.endswith('.one') and k[:-4] + '.other' in ms_raw:
        return ms_raw[k[:-4] + '.other']
    return v


ms = {k: ms_value(k, v) for k, v in en.items()}
# plural forms that exist only in one language
for k, v in ms_raw.items():
    if k not in ms and k.rsplit('.', 1)[0] + '.other' in en:
        ms[k] = v


# The web app runs on computers too: say "device" where the Android text says "phone".
WEB_EN = [("this phone's", "this device's"), ("This phone's", "This device's"), ("this phone", "this device"), ("This phone", "This device"),
          ("the phone's", "the device's"), ("the phone", "the device"), ("your phone", "your device"), ("Follows the device", "Follows the browser")]
WEB_MS = [("telefon ini", "peranti ini"), ("Telefon ini", "Peranti ini"), ("Ikut telefon", "Ikut pelayar")]
# Device unlock on the web uses passkeys (Windows Hello, Touch ID, fingerprint, face or PIN).
WEB_OVERRIDES_EN = {
    "a.settings_biometric": "Unlock with this device",
    "a.settings_biometric_body": "Use Windows Hello, fingerprint, face or PIN on this device (a passkey with hardware-protected encryption) instead of typing the master password. An enabled Authenticator is still required.",
    "a.settings_biometric_on": "On for this device",
    "a.bio_enabled": "Device unlock is on",
    "a.gen_subtitle": "Strong, random passwords and passphrases generated on this device.",
}
WEB_OVERRIDES_MS = {
    "a.settings_biometric": "Buka kunci dengan peranti ini",
    "a.settings_biometric_body": "Guna Windows Hello, cap jari, wajah atau PIN pada peranti ini (passkey dengan penyulitan yang dilindungi perkakasan) dan bukan menaip kata laluan induk. Authenticator yang aktif masih diperlukan.",
    "a.settings_biometric_on": "Hidup untuk peranti ini",
    "a.bio_enabled": "Buka kunci peranti dihidupkan",
}


def webify(data: dict, subs, overrides) -> dict:
    out = {}
    for k, v in data.items():
        for x, y in subs:
            v = v.replace(x, y)
        out[k] = overrides.get(k, v)
    return out


en = webify(en, WEB_EN, WEB_OVERRIDES_EN)
ms = webify(ms, WEB_MS, WEB_OVERRIDES_MS)


def write(name: str, data: dict, typed: bool):
    lines = ['/* Generated by scripts/android-strings.py from the Android app. Do not edit by hand. */']
    if typed:
        lines.append("import type { androidEn } from './android-en';")
        lines.append('')
        lines.append('export const androidMs: Record<keyof typeof androidEn, string> = {')
    else:
        lines.append('')
        lines.append('export const androidEn = {')
    for k in sorted(data):
        if typed and k not in en:
            continue
        lines.append('  %s: %s,' % (json.dumps(k), json.dumps(data[k], ensure_ascii=False)))
    lines.append('}' + (';' if typed else ' as const;'))
    open(os.path.join(ROOT, 'src', 'i18n', name), 'w', encoding='utf8', newline='\n').write('\n'.join(lines) + '\n')


write('android-en.ts', en, False)
write('android-ms.ts', ms, True)
print('strings: %d (Malay translated: %d)' % (len(en), sum(1 for k in en if k in ms_raw)))
